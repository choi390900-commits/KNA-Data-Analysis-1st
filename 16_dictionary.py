# 1) 센서명을 키(key), 측정값을 값(value)으로 딕셔너리 지정
sensors = { 
    "모터온도": 78,
    "진동": 0.5 
    }

# 2) 키로 값을 꺼내고 새 키로 추가, 기존 키로 수정
print(sensors["진동"])          # 값꺼내기
print(sensors.get("진동", 0))   # 값 안전하게 꺼내기

sensors["압력"] = 95      # 있던 키를 엄급하여 추가
sensors["진동"] = 0.3     # 있던 키를 언급하여 수정

print(sensors)

# 3) get으로 없는 키를 기본값으로 조회, in으로 키 존재 확인
print(sensors.get("면적", -1)) # 면적 key는 존재하지 않아서 -1로 대체
print("진동" in sensors) # 존재하는 key
print("면적" in sensors) # 존재하지않는 key

