import matplotlib.pyplot as plt
import pandas as pd
import numpy as np

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False

np.random.seed(42)
temp_data = np.random.uniform(50, 90, 50)
noise_data = temp_data * 0.8 + np.random.normal(0, 3, 50)

df = pd.DataFrame({'온도': temp_data, '소음': noise_data})

plt.figure(figsize=(7, 5))

plt.scatter(df['온도'], df['소음'], color='darkorange', alpha=0.8, edgecolors='black')

plt.title('온도와 소음 센서 간 관계 분석')
plt.xlabel('온도(℃)')
plt.ylabel('소음(dB)')

plt.grid(True, linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()

corr_value = df['온도'].corr(df['소음'])
print(f"▶ 두 변수의 상관계수: {corr_value:.2f}")
print("▶ 관계 해석: 점들이 우상향 형태를 띠므로, 온도가 올라갈수록 소음도 함께 커지는 '양의 상관관계'를 보입니다.")