"""#실습4번"""

import matplotlib.pyplot as plt
import pandas as pd
import numpy as np

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False

np.random.seed(10)
temp_data = np.random.normal(loc=70, scale=5.6, size=100)
temp_data = (temp_data - temp_data.mean()) / temp_data.std(ddof=1) * 5.6 + 70.0
temp_data = np.sort(temp_data)
temp_data[-1], temp_data[-2], temp_data[-3] = 79.2, 78.1, 77.5
df = pd.DataFrame({'온도': temp_data})

mean_temp = df['온도'].mean()
std_temp = df['온도'].std()

abnormal_df = df[df['온도'] >= 78]
abnormal_count = len(abnormal_df)

print(f"▶ 온도 평균: {mean_temp:.1f} · 표준편차: {std_temp:.1f}")
print(f"▶ 78도 이상 이상 설비 수: {abnormal_count}대")

plt.figure(figsize=(8, 4.5))

plt.hist(df['온도'], bins=15, color='cornflowerblue', edgecolor='black')

plt.axvline(mean_temp, color='green', linestyle='--', linewidth=2, label=f'평균 ({mean_temp:.1f}℃)')
plt.axvline(78, color='red', linestyle=':', linewidth=2, label='이상 기준 (78℃ 이상)')

plt.title('센서값 온도 분포 히스토그램')
plt.xlabel('온도(℃)')
plt.ylabel('설비 수(대)')
plt.legend()

plt.tight_layout()
plt.show()

