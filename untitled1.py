import matplotlib.pyplot as plt
import pandas as pd
import numpy as np

plt.rc('font', family='Malgun Gothic')
plt.rcParams['axes.unicode_minus'] = False

np.random.seed(42)
temp_data = np.random.uniform(50, 90, 60)
vib_data = temp_data * 0.06 - 1.5 + np.random.normal(0, 0.4, 60)

df = pd.DataFrame({'온도': temp_data, '진동': vib_data})

df['상태'] = ['점검' if v >= 3.0 else '정상' for v in df['진동']]

plt.figure(figsize=(8, 5))

normal_df = df[df['상태'] == '정상']
check_df = df[df['상태'] == '점검']

plt.scatter(normal_df['온도'], normal_df['진동'], color='blue', alpha=0.7, label='정상')
plt.scatter(check_df['온도'], check_df['진동'], color='red', alpha=0.7, label='점검')

plt.axhline(y=3.0, color='red', linestyle='--', linewidth=1.5, label='임계 기준선 (3.0)')

plt.title('센서 온도와 진동의 관계 분석 (산점도)')
plt.xlabel('온도(℃)')
plt.ylabel('진동(mm/s)')

plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

