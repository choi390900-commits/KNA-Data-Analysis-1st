# 실습 5. 그룹별 평균 비교와 정렬
# 그룹별 평균을 구해 정렬로 두드러진 그룹 찾기
# 그룹별 평균을 구하고 정렬해 두드러진 그룹 찾기

# · 설비로 그룹을 나눠 진동 평균 집계
# 밸브상태 그룹별로 진동의 평균
print(df.groupby('밸브상태')['진동'].mean().round(3))
# 밸브상태
# 경미    0.617
# 심각    0.629
# 정상    0.609
# 지연    0.621

# · 집계 결과에 정렬을 이어 붙여 내림차순으로 정렬
# 앞선 평균결과에 맞춰서 심각 > 지연 > 경미 > 정상 순서로 출력
print(df.groupby('밸브상태')['진동'].mean().round(3).sort_values(ascending=False))
# 밸브상태
# 심각    0.629
# 지연    0.621
# 경미    0.617
# 정상    0.609

