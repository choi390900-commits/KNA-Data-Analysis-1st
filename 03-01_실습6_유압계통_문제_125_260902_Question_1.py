import pandas as pd

tag_df = pd.read_csv('data/03-01_유압·열설비_신호_계통태그목록.csv')
data_df = pd.read_csv('data/03-01_유압·열설비_신호_유압운전.csv')

hyd_tags = tag_df[tag_df['tag'].str.startswith('HYD', na=False)]
print("=== [Step 1] 유압 계통 주요 태그 ===")
print(hyd_tags[['tag', 'physical_qty', 'unit', 'circuit_position']])

target_cols = ['HYD01_PRESS_PUMP', 'HYD01_FLOW', 'HYD01_OILTEMP', 'HYD01_LEVEL', 'HYD01_PUMP_CURRENT']

first_30_mean = data_df[target_cols].iloc[:30].mean()
last_10_mean = data_df[target_cols].iloc[-10:].mean()

diff_direction = ["증가" if last > first else "감소" for first, last in zip(first_30_mean, last_10_mean)]

step2_result = pd.DataFrame({
    '정상 30일 평균': first_30_mean,
    '최근 10일 평균': last_10_mean,
    '변화 방향': diff_direction
})
print("\n=== [Step 2] 평균 비교 ===")
print(step2_result)

data_df['FILTER_DP'] = data_df['HYD01_PRESS_FILT_IN'] - data_df['HYD01_PRESS_FILT_OUT']

dp_periods = {
    '1~30일': (data_df['FILTER_DP'].iloc[0], data_df['FILTER_DP'].iloc[29]),
    '31~60일': (data_df['FILTER_DP'].iloc[30], data_df['FILTER_DP'].iloc[59]),
    '61~90일': (data_df['FILTER_DP'].iloc[60], data_df['FILTER_DP'].iloc[89]),
}

print("\n=== [Step 3] 구간별 차압 증가 ===")
for period, (start, end) in dp_periods.items():
    print(f"{period} | 시작: {start:.2f} | 종료: {end:.2f} | 증가폭: {end - start:.2f}")

