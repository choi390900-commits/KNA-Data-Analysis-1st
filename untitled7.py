import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv('data/cmapss_fd001_sample.csv')
engine1 = df[df['unit_nr'] == 1]
x = engine1['time_cycles']
y_original = engine1['s_3']

y_std = y_original.rolling(window=20).std()

fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 8), sharex=True)

ax1.plot(x, y_original, color='gray', label='원본 (s_3)', linewidth=1.5)
ax1.set_title('원본 데이터 시계열', fontsize=14)
ax1.set_ylabel('센서 값', fontsize=12)
ax1.legend(loc='upper left')
ax1.grid(True, linestyle='--', alpha=0.6)

ax2.plot(x, y_std, color='red', label='이동표준편차 (window=20)', linewidth=2)
ax2.set_title('이동표준편차를 통한 변동성 분석', fontsize=14)
ax2.set_xlabel('가동 회차 (Time Cycles)', fontsize=12)
ax2.set_ylabel('표준편차 값', fontsize=12)

ax2.axvspan(150, x.max(), color='yellow', alpha=0.3, label='불안정(변동성 급증) 구간')
ax2.legend(loc='upper left')
ax2.grid(True, linestyle='--', alpha=0.6)

plt.tight_layout()
plt.show()