import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv('data/cmapss_fd001_sample.csv')
engine1 = df[df['unit_nr'] == 1]
x = engine1['time_cycles']

sensors = ['s_2', 's_7']
colors = ['red', 'blue']

plt.figure(figsize=(10, 5))

for sensor, color in zip(sensors, colors):

    y_ma = engine1[sensor].rolling(window=20).mean()

    y_ma_scaled = (y_ma - y_ma.min()) / (y_ma.max() - y_ma.min())

    plt.plot(x, y_ma_scaled, color=color, label=f'{sensor} 이동평균 (window=20)', linewidth=2)

plt.title('여러 센서의 추세 방향 비교 (0~1 스케일 조정)', fontsize=14)
plt.xlabel('가동 회차 (Time Cycles)', fontsize=12)
plt.ylabel('센서 값 (정규화 됨)', fontsize=12)
plt.legend(fontsize=12)
plt.grid(True, linestyle='--', alpha=0.6)

plt.show()

