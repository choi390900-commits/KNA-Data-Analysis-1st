import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv('data/cmapss_fd001_sample.csv')
engine2 = df[df['unit_nr'] == 2]
x = engine2['time_cycles']
y_original = engine2['s_2']

plt.figure(figsize=(12, 6))
plt.plot(x, y_original, color='lightgray', label='원본 (s_2)', linewidth=1.2)

windows = [5, 20, 50]
colors = ['green', 'orange', 'red']

for w, color in zip(windows, colors):
    y_ma = y_original.rolling(window=w).mean()
    plt.plot(x, y_ma, color=color, label=f'이동평균 (window={w})', linewidth=2)

plt.title('윈도우 크기별 이동평균선 비교 (5 vs 20 vs 50)', fontsize=14)
plt.xlabel('가동 회차 (Time Cycles)', fontsize=12)
plt.ylabel('센서 값', fontsize=12)
plt.legend(fontsize=11)
plt.grid(True, linestyle='--', alpha=0.6)

plt.show()

