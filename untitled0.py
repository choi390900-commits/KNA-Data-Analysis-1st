import pandas as pd
import matplotlib.pyplot as plt

plt.rcParams['font.family'] = 'Malgun Gothic'
plt.rcParams['axes.unicode_minus'] = False

data = {
    '일자': [1, 2, 3, 4, 5],
    '온도': [70, 72, 75, 78, 82],
    '소음': [65, 68, 70, 75, 80],
    '진동': [0.7, 0.75, 0.8, 0.9, 1.2]
}
df_c = pd.DataFrame(data)

plt.figure(figsize=(10, 5))

plt.plot(df_c['일자'], df_c['온도'], color='red', marker='o', label='온도')
plt.plot(df_c['일자'], df_c['소음'], color='blue', marker='s', label='소음')

plt.plot(df_c['일자'], df_c['진동'] * 100, color='green', marker='^', linestyle='--', label='진동(x100)')

plt.title('C호기 상태 종합(온도·진동·소음) 추세선 비교')
plt.xlabel('일자')
plt.ylabel('측정값')
plt.legend(loc='upper left')
plt.grid(True, alpha=0.3)

plt.show()