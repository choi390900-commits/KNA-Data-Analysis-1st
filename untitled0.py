"""#실습5번"""

import pandas as pd
import matplotlib.pyplot as plt

plt.rcParams['font.family'] = 'Malgun Gothic'
plt.rcParams['axes.unicode_minus'] = False

data = {
    '일자': [1, 2, 3, 4, 5]*3,
    '설비명': ['A호기']*5 + ['B호기']*5 + ['C호기']*5,
    '온도': [75, 76, 78, 80, 83, 70, 72, 71, 74, 75, 62, 63, 65, 68, 72]
}
df = pd.DataFrame(data)

plt.figure(figsize=(10, 5))

machines = ['A호기', 'B호기', 'C호기']
colors = ['red', 'blue', 'green']

for machine, color in zip(machines, colors):
    df_machine = df[df['설비명'] == machine]

    plt.plot(df_machine['일자'], df_machine['온도'], color=color, marker='o', label=machine)

plt.title('세 설비 일자별 온도 비교')
plt.xlabel('일자')
plt.ylabel('온도(℃)')
plt.legend(loc='upper left')
plt.grid(True, alpha=0.3)

plt.savefig('세_설비_온도_비교.png', dpi=150)

plt.show()

