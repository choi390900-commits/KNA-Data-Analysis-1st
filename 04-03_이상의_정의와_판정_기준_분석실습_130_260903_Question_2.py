import pandas as pd
import matplotlib.pyplot as plt


df = pd.read_csv('data/04-03_이상의_정의_진동데이터.csv')

df_active = df[df['가동여부'] == 1]

plt.figure(figsize=(10, 5))
plt.plot(df_active['일자'], df_active['진동RMS'], label='Vibration RMS', color='blue')
plt.axhline(y=4.5, color='red', linestyle='--', label='Threshold (4.5 mm/s)')

plt.xlabel('Date (Day)')
plt.ylabel('Vibration RMS (mm/s)')
plt.title('Vibration RMS Trend Over Time (Active Only)')
plt.legend()
plt.grid(True)
plt.show()

# [그래프 분석 기록]
