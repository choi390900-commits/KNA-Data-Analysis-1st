# 실습

import pandas as pd

tag_df = pd.read_csv('data/03-01_유압·열설비_신호_계통태그목록.csv')
data_df = pd.read_csv('data/03-01_유압·열설비_신호_가열로온도.csv')

tag_df.columns = tag_df.columns.str.strip()
data_df.columns = data_df.columns.str.strip()

tag_col = '태그명' if '태그명' in tag_df.columns else tag_df.columns[0]
fur_tags = tag_df[tag_df[tag_col].astype(str).str.startswith('FUR')]
print("=== [Step 1] FUR 태그 목록 ===")
print(fur_tags)

for z in ['Z1', 'Z2', 'Z3']:
    left_col = [c for c in data_df.columns if z in c and ('LEFT' in c or '_L' in c or '좌' in c)][0]
    right_col = [c for c in data_df.columns if z in c and ('RIGHT' in c or '_R' in c or '우' in c)][0]
    data_df[f'{z}_DEV'] = data_df[right_col] - data_df[left_col]

print("\n=== [Step 2] 앞 20일 구간 평균 편차 ===")
for z in ['Z1', 'Z2', 'Z3']:
    avg_dev = data_df[f'{z}_DEV'].iloc[:20].mean()
    print(f"{z} 평균 편차: {avg_dev:.2f}")

print("\n=== [Step 3] 시점별 좌우 편차 (1일, 20일, 40일, 60일차) ===")
days_idx = [0, 19, 39, 59]
step3_df = pd.DataFrame({
    '시점': ['1일차', '20일차', '40일차', '60일차'],
    'Z1 편차': data_df['Z1_DEV'].iloc[days_idx].values,
    'Z2 편차': data_df['Z2_DEV'].iloc[days_idx].values,
    'Z3 편차': data_df['Z3_DEV'].iloc[days_idx].values
})
print(step3_df)

