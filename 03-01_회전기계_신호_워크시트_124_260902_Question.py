#  구분        | 물리량 | 그 물리량을 고른 이유
# ------------|-------|--------------------------------
#  주 신호     | 진동   | 질량 불평형은 회전 주파수 와 동일한 주기의 명확한 진동을 발생시킴
#  확인 신호 1 | 회전수 | 진동의 크기는 회전수의 제곱에 비례하므로, 현재 회전수 상태를 반드시 확인해야 함
#  확인 신호 2 | 전류   | 불평형으로 인한 회전 저항 증가 및 공기 역학적 부하 변화가 모터 전류량에 반영됨


# [Step 2] 지표·요약 방식·위치·주기 결정

#  주 신호 지표 (변위/속도/가속도) : 속도          이유: 불평형은 회전 주파수 대역에서 발생하며, ISO 10816 등 국제 규격에서도 속도를 피로도 평가 지표로 사용함
#  요약 방식 (RMS/PEAK)           : RMS           이유: 불평형 진동은 지속적인 정현파 형태를 띄므로, 전체 진동 에너지를 나타내는 RMS가 가장 안정적인 지표임
#  측정 위치                       : 1번 팬 베어링 하우징
#  측정 방향                       : 반경 방향 중 수평 방향 
#  필요 저장 주기                  : 1시간 ~ 1일   이유: 분진 축적은 장기간에 걸쳐 서서히 발생하므로 긴 주기의 추세 모니터링이 적합함


