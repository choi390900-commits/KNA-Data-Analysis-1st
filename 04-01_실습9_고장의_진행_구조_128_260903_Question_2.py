# 2. 전체 사례 수를 출력하세요.

df = pd.read_csv('data/04-01_고장의_진행_구조_고장사례.csv')
print(f"전체 사례 수: {len(df)}건\n")


# ============================================================
# 실습 1 - P-F 간격과 점검 주기
# ============================================================

# [상황]
# 고장을 발견한 뒤 확인·진단·부품 조달·대기·정비 작업까지
# 총 20일이 필요하다고 가정합니다.

리드타임 = 20


# ------------------------------------------------------------
# Step 1. 대응 가능 여부 판정
# ------------------------------------------------------------

# [문제]
# 각 사례에 대해 P-F 간격이 리드타임 20일보다 긴지 확인하세요.
#
# 판정 기준
# - P-F 간격 > 20일  → 대응 가능
# - P-F 간격 <= 20일 → 대응 불가

# 새로운 컬럼 이름은 "대응가능"으로 만드세요.
#
# 출력할 컬럼
# - 사례ID
# - 설비
# - PF간격_일
# - 대응가능

df["대응가능"] = df["PF간격_일"].apply(lambda x: "대응 가능" if x > 리드타임 else "대응 불가")
print("=== [실습1 - Step1] 대응 가능 여부 판정 ===")
print(df[["사례ID", "설비", "PF간격_일", "대응가능"]])
print("\n")

# ------------------------------------------------------------
# Step 2. 대응 불가 사례 찾기
# ------------------------------------------------------------

# [문제]
# 리드타임 20일 기준으로 대응이 불가능한 사례의
# 사례ID만 찾아서 출력하세요.

print("=== [실습1 - Step2] 대응 불가 사례 ===")
unmanageable_cases = df[df['대응가능'] == '대응 불가']['사례ID'].tolist()
print(f"대응 불가 사례ID: {unmanageable_cases}")
print("\n")

# ------------------------------------------------------------
# Step 3. 권장 점검 주기 계산
# ------------------------------------------------------------

# [문제]
# 예지보전의 '절반 규칙'을 적용해
# 권장 점검 주기를 계산하세요.
#
# 절반 규칙
#   권장 점검 주기 = P-F 간격 / 2
#
# 새로운 컬럼 이름은 "권장점검주기_일"로 만드세요.
#
# 출력할 컬럼
# - 사례ID
# - 설비
# - PF간격_일
# - 권장점검주기_일
# - 대응가능

df['권장점검주기_일'] = df['PF간격_일'] / 2
print("=== [실습1 - Step3] 권장 점검 주기 계산 ===")
print(df[['사례ID', '설비', 'PF간격_일', '권장점검주기_일', '대응가능']])
print("\n")

# ------------------------------------------------------------
# Step 4. 저장 주기가 절반 규칙을 만족하는지 확인
# ------------------------------------------------------------

# [문제]
# 현재 데이터 저장 주기가 권장 점검 주기를 만족하는지 확인하세요.
#
# 조건
# 1. 데이터저장여부가 "Y"여야 합니다.
# 2. 저장주기_분을 '일(day)' 단위로 변환하세요.
# 3. 실제 저장 주기가 권장점검주기_일보다 짧거나 같아야 합니다.
#
# 새로운 컬럼 이름은 "저장주기_적정"으로 만드세요.
#
# 마지막으로 저장 주기가 적정한 사례의 사례ID만 출력하세요.

def check_storage_cycle(row):
    if row['데이터저장여부'] != 'Y':
        return False
    저장주기_일 = row['저장주기_분'] / 1440 
    return 저장주기_일 <= row['권장점검주기_일']

df['저장주기_적정'] = df.apply(check_storage_cycle, axis=1)

print("=== [실습1 - Step4] 저장 주기가 적정한 사례ID ===")
proper_storage_cases = df[df['저장주기_적정'] == True]['사례ID'].tolist()
print(f"저장주기 적정 사례ID: {proper_storage_cases}")
print("\n")



# ============================================================
# 실습 2 - 고장의 예측 가능성 분류
# ============================================================

# [상황]
# 같은 고장이라도 현장의 대응 리드타임에 따라
# 예측 가능 여부가 달라질 수 있습니다.
#
# 케이스 A : 리드타임 7일
# 케이스 B : 리드타임 30일


# ------------------------------------------------------------
# Step 1. 판정 규칙 만들기
# ------------------------------------------------------------

# [문제]
# 아래 판정 규칙을 함수로 구현하세요.
#
# Q1. 열화 과정이 물리적으로 존재하는가?
# - 손상형태가 "과부하 파단" 또는 "이물"이면
#   → "물리적 돌발"
#
# Q2. P-F 간격이 리드타임보다 긴가?
# - PF간격_일 <= 리드타임이면
#   → "간격 부족형"
#
# Q3. 해당 신호가 데이터에 저장되는가?
# - 데이터저장여부가 "Y"가 아니면
#   → "측정 부재형"
#
# 위 조건에 모두 해당하지 않으면
#   → "예측 가능형"
#
# 함수 이름은 자유롭게 정해도 됩니다.
# 함수는 '한 행'과 '리드타임'을 입력받아
# 판정 문자열을 반환하도록 작성해 보세요.

def judge_predictability(row, lead_time):
    if row['손상형태'] in ['과부하 파단', '이물']:
        return "물리적 돌발"
    elif row['PF간격_일'] <= lead_time:
        return "간격 부족형"
    elif row['데이터저장여부'] != 'Y':
        return "측정 부재형"
    else:
        return "예측 가능형"



# ------------------------------------------------------------
# Step 2. 케이스 A와 케이스 B 판정
# ------------------------------------------------------------

# [문제]
# 위에서 만든 판정 함수를 사용해
# 두 개의 판정 컬럼을 만드세요.
#
# 케이스 A : 리드타임 7일
#   → 컬럼명 "케이스A_판정"
#
# 케이스 B : 리드타임 30일
#   → 컬럼명 "케이스B_판정"
#
# 아래 컬럼을 함께 출력하세요.
# - 사례ID
# - 설비
# - 손상형태
# - PF간격_일
# - 데이터저장여부
# - 케이스A_판정
# - 케이스B_판정

df['케이스A_판정'] = df.apply(lambda row: judge_predictability(row, 7), axis=1)
df['케이스B_판정'] = df.apply(lambda row: judge_predictability(row, 30), axis=1)

print("=== [실습2 - Step2] 케이스 A와 B 판정 결과 ===")
print(df[['사례ID', '설비', '손상형태', 'PF간격_일', '데이터저장여부', '케이스A_판정', '케이스B_판정']])
print("\n")


# ------------------------------------------------------------
# Step 3. 리드타임 때문에 판정이 바뀐 사례 찾기
# ------------------------------------------------------------

# [문제]
# 케이스 A와 케이스 B의 판정이 서로 다른 사례만 찾아
# 사례ID를 출력하세요.
#
# 추가 질문
# - 왜 리드타임이 길어지면 같은 고장도
#   예측 가능형에서 간격 부족형으로 바뀔 수 있을까요?

print("=== [실습2 - Step3] 리드타임 변경으로 판정이 바뀐 사례 ===")
changed_cases = df[df['케이스A_판정'] != df['케이스B_판정']]['사례ID'].tolist()
print(f"판정 변경 사례ID: {changed_cases}")
print("\n")



# ------------------------------------------------------------
# Step 4. 예측 가능형의 목표 조기 경보 시점 계산
# ------------------------------------------------------------

# [문제]
# 케이스 A에서 "예측 가능형"으로 판정된 사례만 선택하세요.
#
# 목표 경보 시점은 다음과 같이 정합니다.
#
#   목표 경보 시점 = P-F 간격의 50%
#
# 계산한 값은 반올림한 뒤 정수로 변환하고,
# 새로운 컬럼 이름은 "목표경보_일전"으로 만드세요.
#
# 출력할 컬럼
# - 사례ID
# - 설비
# - PF간격_일
# - 목표경보_일전

caseA_predictable = df[df['케이스A_판정'] == '예측 가능형'].copy()
caseA_predictable['목표경보_일전'] = (caseA_predictable['PF간격_일'] * 0.5).round().astype(int)

print("=== [실습2 - Step4] 목표 조기 경보 시점 ===")
print(caseA_predictable[['사례ID', '설비', 'PF간격_일', '목표경보_일전']])
print("\n")



# ------------------------------------------------------------
# Step 5. 예측 불가 사례의 대응 방향 정하기
# ------------------------------------------------------------

# [문제]
# 케이스 B에서 "예측 가능형"이 아닌 사례만 선택하세요.
#
# 아래 기준에 따라 대응 방향을 연결하세요.
#
# 물리적 돌발
#   → 이중화 또는 정기 교체
#
# 간격 부족형
#   → 보호 로직 또는 자동 정지
#
# 측정 부재형
#   → 계측 개선 또는 저장 주기 조정
#
# 새로운 컬럼 이름은 "대응방향"으로 만드세요.
#
# 출력할 컬럼
# - 사례ID
# - 설비
# - 케이스B_판정
# - 대응방향

caseB_unpredictable = df[df['케이스B_판정'] != '예측 가능형'].copy()

def determine_action(status):
    if status == '물리적 돌발':
        return '이중화 또는 정기 교체'
    elif status == '간격 부족형':
        return '보호 로직 또는 자동 정지'
    elif status == '측정 부재형':
        return '계측 개선 또는 저장 주기 조정'
    return ''

caseB_unpredictable['대응방향'] = caseB_unpredictable['케이스B_판정'].apply(determine_action)

print("=== [실습2 - Step5] 예측 불가 사례의 대응 방향 ===")
print(caseB_unpredictable[['사례ID', '설비', '케이스B_판정', '대응방향']])
print("\n")



